    private void showPull(float dy) {
        if (dy <= 0) {
            if (!refreshing) refreshIndicator.setVisibility(View.GONE);
            return;
        }
        float threshold = dp(PULL_THRESHOLD_DP);
        refreshIndicator.setVisibility(View.VISIBLE);
        refreshIndicator.setTranslationY(Math.min(dy * 0.5f, dp(96)) - dp(36));
        refreshIndicator.setAlpha(Math.min(1f, dy / threshold));
    }


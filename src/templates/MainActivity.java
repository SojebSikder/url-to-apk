    /** Lightweight pull-to-refresh that observes touches without stealing them from the page. */
    private class RefreshLayout extends FrameLayout {
        private float startY;
        private boolean tracking;

        RefreshLayout(Context context) {
            super(context);
        }

        @Override
        public boolean dispatchTouchEvent(MotionEvent ev) {
            if (Config.PULL_TO_REFRESH && webView != null && customView == null) {
                switch (ev.getActionMasked()) {
                    case MotionEvent.ACTION_DOWN:
                        startY = ev.getY();
                        tracking = !refreshing && (mainFrameError || webView.getScrollY() == 0);
                        break;
                    case MotionEvent.ACTION_MOVE:
                        if (tracking) {
                            if (!mainFrameError && webView.getScrollY() > 0) {
                                cancel();
                            } else {
                                showPull(ev.getY() - startY);
                            }
                        }
                        break;
                    case MotionEvent.ACTION_UP:
                        if (tracking) {
                            tracking = false;
                            boolean atTop = mainFrameError || webView.getScrollY() == 0;
                            if (atTop && ev.getY() - startY > dp(PULL_THRESHOLD_DP)) {
                                startRefreshing();
                            } else if (!refreshing) {
                                refreshIndicator.setVisibility(View.GONE);
                            }
                        }
                        break;
                    case MotionEvent.ACTION_POINTER_DOWN:
                    case MotionEvent.ACTION_CANCEL:
                        cancel();
                        break;
                    default:
                        break;
                }
            }
            return super.dispatchTouchEvent(ev);
        }

        private void cancel() {
            tracking = false;
            if (!refreshing) refreshIndicator.setVisibility(View.GONE);
        }
    }

